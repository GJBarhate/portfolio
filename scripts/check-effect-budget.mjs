#!/usr/bin/env node
/**
 * check-effect-budget.mjs — T-060.
 *
 * The effect system's failure mode is not any single effect. It is the tenth
 * one, added by someone who checked that *their* effect was cheap. This sums
 * the declared cost of everything that runs at each tier and fails when the
 * total exceeds the frame budget from Appendix B.
 *
 * It also enforces the descriptor contract, because a registry entry that
 * omits its tier-0 behaviour is how "additive, never load-bearing" quietly
 * stops being true.
 *
 * Side effect: writes `docs/effects.md` from the registry, so the
 * documentation cannot drift from the thing it documents.
 */
import { writeFileSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname } from 'node:path'
import { EFFECTS, TIER_BUDGETS, TIER_SCALE, totalCost, runsAtTier } from '../src/lib/effects/registry.js'

const DOCS = fileURLToPath(new URL('../docs/effects.md', import.meta.url))
const failures = []

// ── the descriptor contract ───────────────────────────────────────────────
const KINDS = new Set(['webgl', 'canvas2d', 'css', 'waapi', 'scroll-driven', 'dom'])
const seen = new Set()

for (const effect of EFFECTS) {
  const where = `effect "${effect.id}"`
  if (!effect.id || seen.has(effect.id)) failures.push(`${where}: missing or duplicate id`)
  seen.add(effect.id)
  if (!KINDS.has(effect.kind)) failures.push(`${where}: unknown kind "${effect.kind}"`)
  // Law 1 — meaning before motion.
  if (!effect.purpose || effect.purpose.length < 30) {
    failures.push(`${where}: purpose must say what this tells the visitor, not that it looks nice`)
  }
  // Law 4 — four tiers, four defined behaviours.
  for (const tier of [3, 2, 1, 0]) {
    if (!effect.tiers?.[tier]) failures.push(`${where}: no behaviour declared at tier ${tier}`)
  }
  // Law 2 — nothing may be load-bearing, so tier 0 must be survivable.
  if (effect.tiers?.[0] && !/^(off|none|static|native|instant|no animation|a static)/i.test(effect.tiers[0])) {
    failures.push(`${where}: tier 0 must degrade to a non-animated state, got "${effect.tiers[0]}"`)
  }
  for (const field of ['gpuMs', 'cpuMs', 'bytes']) {
    if (typeof effect.cost?.[field] !== 'number') failures.push(`${where}: cost.${field} must be a number`)
  }
  if (!Array.isArray(effect.respects) || effect.respects.length === 0) {
    failures.push(`${where}: must declare at least one preference axis it respects`)
  }
}

// ── the budget ────────────────────────────────────────────────────────────
const rows = []
for (const tier of [3, 2, 1, 0]) {
  const total = totalCost(tier)
  const budget = TIER_BUDGETS[tier]
  const active = EFFECTS.filter((e) => runsAtTier(e, tier)).length
  rows.push({ tier, active, ...total, budget })
  if (total.gpuMs > budget.gpuMs + 1e-9) {
    failures.push(`tier ${tier}: GPU ${total.gpuMs.toFixed(2)} ms > ${budget.gpuMs} ms budget`)
  }
  if (total.cpuMs > budget.cpuMs + 1e-9) {
    failures.push(`tier ${tier}: CPU ${total.cpuMs.toFixed(2)} ms > ${budget.cpuMs} ms budget`)
  }
}

console.log('\nEffect cost by tier (per frame)')
console.log('─'.repeat(62))
for (const row of rows) {
  const ok = row.gpuMs <= row.budget.gpuMs + 1e-9 && row.cpuMs <= row.budget.cpuMs + 1e-9
  console.log(
    `${ok ? '✓' : '✗'} tier ${row.tier}  ${String(row.active).padStart(2)} active   ` +
    `GPU ${row.gpuMs.toFixed(2).padStart(5)} / ${String(row.budget.gpuMs).padStart(4)} ms   ` +
    `CPU ${row.cpuMs.toFixed(2).padStart(5)} / ${String(row.budget.cpuMs).padStart(4)} ms`
  )
}
console.log('─'.repeat(62))

// ── generated documentation ───────────────────────────────────────────────
const doc = `# Effects

<!-- GENERATED by scripts/check-effect-budget.mjs from src/lib/effects/registry.js.
     Do not edit by hand: the registry is the source, and this file exists so
     the documentation cannot drift from what actually ships. -->

Every effect on the site declares what it is for, what it does at each of the
four graphics tiers, and what it costs. The sum is asserted in CI, which is
what stops the tenth effect from being the one nobody measured.

## Cost by tier

| Tier | Effects running | GPU / frame | Budget | CPU / frame | Budget |
|---|---:|---:|---:|---:|---:|
${rows.map((r) => `| ${r.tier} | ${r.active} | ${r.gpuMs.toFixed(2)} ms | ${r.budget.gpuMs} ms | ${r.cpuMs.toFixed(2)} ms | ${r.budget.cpuMs} ms |`).join('\n')}

Tier 2 and below run reduced versions rather than the full effect, so their
cost is scaled by ${JSON.stringify(TIER_SCALE)} — the same factors the tier
descriptions promise (half resolution, half frame rate).

## The register

${EFFECTS.map((e) => `### \`${e.id}\` · ${e.kind}

**Purpose.** ${e.purpose}

| Tier 3 | Tier 2 | Tier 1 | Tier 0 |
|---|---|---|---|
| ${e.tiers[3]} | ${e.tiers[2]} | ${e.tiers[1]} | ${e.tiers[0]} |

Cost at tier 3: **${e.cost.gpuMs} ms GPU**, **${e.cost.cpuMs} ms CPU**, ${(e.cost.bytes / 1024).toFixed(1)} KB.
Requires: ${e.requires.length ? e.requires.map((r) => `\`${r}\``).join(', ') : 'nothing'}.
Respects: ${e.respects.map((r) => `\`${r}\``).join(', ')}.
Group: \`${e.group || 'ungrouped'}\`.
`).join('\n')}
`

mkdirSync(dirname(DOCS), { recursive: true })
writeFileSync(DOCS, doc, 'utf8')

if (failures.length) {
  console.error('Effect budget check failed:')
  for (const failure of failures) console.error(`  ✗ ${failure}`)
  process.exit(1)
}

console.log(`EFFECT-BUDGET-OK — ${EFFECTS.length} effects registered, docs/effects.md regenerated\n`)
